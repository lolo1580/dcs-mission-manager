import assert from 'node:assert/strict';
import { get } from 'svelte/store';
import { loadMappings, saveMappings, mappingAircraft, mappingsLoading, bindings } from '../src/lib/mappings.js';

const pending = [];
globalThis.fetch = (url, options) => new Promise(resolve => pending.push({ url, options, resolve }));
const reply = (index, body) => pending[index].resolve({ ok: true, json: async () => body });
const profile = command => ({ profile: { bindings: [{ model: 'pz55', control: 'MASTER_BAT', command, interface: 'set_state' }] } });
const a = loadMappings('OldJet');
const b = loadMappings('NewJet');
assert.equal(await saveMappings([]), false, 'must not save during an aircraft transition');
reply(2, profile('NEW_COMMAND')); reply(3, { controls: [], available: true }); await b;
reply(0, profile('OLD_COMMAND')); reply(1, { controls: [], available: true }); await a;
assert.equal(get(mappingAircraft), 'NewJet');
assert.equal(get(bindings)[0].command, 'NEW_COMMAND');
assert.equal(get(mappingsLoading), false);
const saving = saveMappings(get(bindings));
const c = loadMappings('ThirdJet');
assert.deepEqual(get(bindings), [], 'old bindings must disappear immediately');
reply(5, profile('THIRD_COMMAND')); reply(6, { controls: [], available: true }); await c;
reply(4, profile('NEW_COMMAND')); await saving;
assert.equal(get(bindings)[0].command, 'THIRD_COMMAND', 'late save must not overwrite another aircraft');
console.log('Panel profile transitions: passed');

const { addBinding, addOutput, outputs, saveProfile } = await import('../src/lib/mappings.js');
globalThis.fetch = async (_url, options) => ({ ok: true, json: async () => ({ profile: JSON.parse(options.body) }) });
bindings.set([{ model: 'pz70', control: 'LCD_WHEEL', mode: 'ALT', command: 'OLD', interface: 'variable_step' }]);
assert.equal(await addBinding({ model: 'pz70', control: 'LCD_WHEEL', mode: 'HDG', command: 'HDG', interface: 'variable_step' }), true);
assert.equal(get(bindings).length, 2);
const oldBinding = get(bindings)[0];
assert.equal(await addBinding({ ...oldBinding, command: 'ALT_NEW' }, oldBinding), true);
assert.equal(get(bindings).length, 2);
assert.equal(get(bindings).find(b => b.mode === 'ALT').command, 'ALT_NEW');
const rules = [{ command: 'GEAR', export: 0, operator: 'eq', value: 1, color: 'green' }];
assert.equal(await addBinding({model:'pz55', control:'MASTER_BAT', command:'BATTERY_SW', interface:'set_state', state_on:0, state_off:1}), true);
assert.equal(await addBinding({model:'pz70', control:'LCD_WHEEL', mode:'CRS', command:'LEFT_DDI_CRS_SW', interface:'set_state', state_on:2, state_off:0, pulse_reset:1}), true);
outputs.set([]);
assert.equal(await addOutput({ model: 'pz55', target: 'LIGHT_GEAR_UPPER', command: 'GEAR', rules }), true);
const portable = JSON.parse(JSON.stringify({ aircraft: get(mappingAircraft), bindings: get(bindings), outputs: get(outputs), displays: [] }));
assert.equal(await saveProfile(portable), true);
assert.deepEqual(get(outputs)[0].rules, rules);
assert.equal(get(bindings).find(b => b.control === 'MASTER_BAT').state_on, 0, 'explicit zero must survive import/export');
assert.equal(get(bindings).find(b => b.control === 'MASTER_BAT').state_off, 1);
assert.equal(get(bindings).find(b => b.mode === 'CRS').pulse_reset, 1, 'spring-centred wheel reset must survive import/export');
console.log('Context editing and portable profile round-trip: passed');
