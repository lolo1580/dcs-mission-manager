// tools/gen-lua-embed.mjs
//
// Generates backend/internal/luafiles/luafiles.go from dcs-lua/** so the single
// binary can install the DCS scripts without shipping a separate folder next to
// it. Contents are base64-encoded, which sidesteps every escaping problem.
//
// The result is passed through gofmt, because gofmt re-aligns composite literals
// and the checked-in file must be gofmt-clean for CI.
//
// Usage:
//   node tools/gen-lua-embed.mjs           # (re)generate
//   node tools/gen-lua-embed.mjs --check   # fail if regeneration would differ
//
// CI runs --check so a Lua edit can never silently drift from the binary.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const srcDir = path.join(root, 'dcs-lua');
const outFile = path.join(root, 'backend', 'internal', 'luafiles', 'luafiles.go');

// Deterministic order, POSIX separators.
function collect(dir, base = '') {
  const entries = [];
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    const rel = base ? `${base}/${name}` : name;
    const stat = fs.statSync(full);
    if (stat.isDirectory()) entries.push(...collect(full, rel));
    else entries.push({ rel, content: fs.readFileSync(full) });
  }
  return entries;
}

const files = collect(srcDir);

const source = `// Code generated by tools/gen-lua-embed.mjs. DO NOT EDIT.
//
// It embeds the DCS-side Lua scripts into the binary so that a single dcsmanager
// executable can install them (see internal/install). Regenerate with:
//
//   node tools/gen-lua-embed.mjs

// Package luafiles exposes the embedded DCS Lua scripts.
package luafiles

import (
	"encoding/base64"
	"sort"
)

// files maps a path relative to dcs-lua/ to its base64-encoded contents.
var files = map[string]string{
${files.map((f) => `\t${JSON.stringify(f.rel)}: ${JSON.stringify(f.content.toString('base64'))},`).join('\n')}
}

// List returns the embedded file paths, sorted.
func List() []string {
	out := make([]string, 0, len(files))
	for name := range files {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}

// Get returns the decoded contents of an embedded file.
func Get(name string) ([]byte, bool) {
	encoded, ok := files[name]
	if !ok {
		return nil, false
	}
	decoded, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		return nil, false
	}
	return decoded, true
}
`;

// gofmt normalises composite-literal alignment; the checked-in file must match.
function gofmt(text) {
  return execFileSync('gofmt', [], { input: text, encoding: 'utf8' });
}

let output;
try {
  output = gofmt(source);
} catch (err) {
  console.error('gofmt failed. Is Go installed and on PATH?');
  console.error(err.message);
  process.exit(1);
}

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('luafiles.go is out of date. Run: node tools/gen-lua-embed.mjs');
    process.exit(1);
  }
  console.log(`luafiles.go is up to date (${files.length} files).`);
  process.exit(0);
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output);
console.log(`Wrote ${outFile} (${files.length} files): ${files.map((f) => f.rel).join(', ')}`);
